def make_answer():
    '''1~9 중 중복없는 3자리 숫자 생성'''
    numbers = list(range(1,10))
    picked_numbers = []

    while len(picked_numbers) < 3:
        pick_number = random.choice(numbers)

        if pick_number not in picked_numbers:
            picked_numbers.append(pick_number)
    return picked_numbers

# 정답 리스트 생성
