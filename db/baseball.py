def get_strike_ball(answerm, guess):
    '''답변하고 응답하고 비교 후 strike, ball값 리턴'''
    input_arr = [int(x) for x in guess]
    # input_arr = []
    # for x in guess:
    #     input_arr.append(int(x))

    # input_arr = list[map(int, guess)]

    strike = 0
    ball = 0

    for i in range(3):
        if input_arr[i] == answerm[i]:
            strike += 1
        elif input_arr[i] in answerm:
            ball += 1

    return strike, ball

